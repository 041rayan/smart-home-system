import 'dart:convert';

/// Represents a fresh, replay-resistant unlock authorization token
/// cryptographically signed by an Android Keystore private key bound to BIOMETRIC_STRONG.
class SignedUnlockToken {
  /// The requested action, e.g. "UNLOCK_DOOR"
  final String action;

  /// Cryptographically random 128-bit hex nonce to prevent replay attacks
  final String nonce;

  /// Timestamp in milliseconds since Unix epoch (UTC)
  final int timestamp;

  /// Unique identifier of the authenticating device / Keystore alias
  final String deviceId;

  /// Base64-encoded ASN.1 DER ECDSA signature generated by Android Keystore
  final String signatureBase64;

  /// Base64-encoded X.509 SubjectPublicKeyInfo of the EC secp256r1 key
  final String publicKeyBase64;

  /// Cryptographic signature algorithm (default: SHA256withECDSA)
  final String algorithm;

  /// The exact canonical UTF-8 JSON payload string that was signed
  final String rawPayload;

  const SignedUnlockToken({
    required this.action,
    required this.nonce,
    required this.timestamp,
    required this.deviceId,
    required this.signatureBase64,
    required this.publicKeyBase64,
    this.algorithm = 'SHA256withECDSA',
    required this.rawPayload,
  });

  /// Factory constructor from JSON
  factory SignedUnlockToken.fromJson(Map<String, dynamic> json) {
    return SignedUnlockToken(
      action: json['action'] as String? ?? 'UNLOCK_DOOR',
      nonce: json['nonce'] as String? ?? '',
      timestamp: json['timestamp'] as int? ?? DateTime.now().millisecondsSinceEpoch,
      deviceId: json['deviceId'] as String? ?? 'android_keystore_knox',
      signatureBase64: json['signatureBase64'] as String? ?? '',
      publicKeyBase64: json['publicKeyBase64'] as String? ?? '',
      algorithm: json['algorithm'] as String? ?? 'SHA256withECDSA',
      rawPayload: json['rawPayload'] as String? ?? '',
    );
  }

  /// Converts to standard JSON map for transmission over BLE GATT or HTTP
  Map<String, dynamic> toJson() {
    return {
      'action': action,
      'nonce': nonce,
      'timestamp': timestamp,
      'deviceId': deviceId,
      'signatureBase64': signatureBase64,
      'publicKeyBase64': publicKeyBase64,
      'algorithm': algorithm,
      'rawPayload': rawPayload,
    };
  }

  /// Serialized JSON string
  String serialize() => jsonEncode(toJson());

  /// Checks if the token was generated recently within [maxAge]
  /// Rejects expired or replay tokens
  bool isFresh({Duration maxAge = const Duration(seconds: 30)}) {
    final now = DateTime.now().millisecondsSinceEpoch;
    final ageMs = (now - timestamp).abs();
    return ageMs <= maxAge.inMilliseconds;
  }

  /// Short truncated representation of signature for UI display
  String get shortSignature {
    if (signatureBase64.length <= 16) return signatureBase64;
    return '${signatureBase64.substring(0, 8)}...${signatureBase64.substring(signatureBase64.length - 8)}';
  }

  /// Short truncated representation of public key for UI display
  String get shortPublicKey {
    if (publicKeyBase64.length <= 16) return publicKeyBase64;
    return '${publicKeyBase64.substring(0, 8)}...${publicKeyBase64.substring(publicKeyBase64.length - 8)}';
  }

  @override
  String toString() {
    return 'SignedUnlockToken(action: $action, nonce: $nonce, timestamp: $timestamp, signature: $shortSignature)';
  }
}
